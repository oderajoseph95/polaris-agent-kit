// `init`: copy the right files for the chosen agent(s) into the user's codebase. Idempotent: running it twice leaves
// the same files; the AGENTS.md block is replaced between its markers; a file we did not generate is never overwritten
// without --force. Never writes outside --dir: a symbolic link or junction anywhere on a path it would write is refused
// (a cloned repository can contain one pointing at your home folder).
import { appendFileSync, existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { createInterface } from "node:readline/promises";
import { BEGIN, END, GENERATED, PKG_ROOT, PLUGIN_CLI } from "./build.mjs";
import { CACHE_DIR, KIT_DIR } from "../lib/project.mjs";

export const AGENTS = ["claude", "cursor", "copilot", "codex", "windsurf"];

const read = (p) => readFileSync(join(PKG_ROOT, p), "utf8").replace(/\r\n/g, "\n");
const pkgName = () => JSON.parse(read("package.json")).name;
const pkgVersion = () => JSON.parse(read("package.json")).version;
const skillName = () => JSON.parse(read("source/meta.json")).skillName;

/** Throws when any EXISTING component of `path` below `root` is a symbolic link or junction (or the path leaves `root`). */
export function assertNoLinks(root, path) {
  const base = resolve(root);
  const relPath = relative(base, resolve(path));
  const parts = relPath.split(sep).filter(Boolean);
  if (isAbsolute(relPath) || parts[0] === ".." || parts.length === 0) throw new Error(`init: refusing to write outside ${root}: ${path}`);
  let cur = base;
  for (const part of parts) {
    cur = join(cur, part);
    let st;
    try { st = lstatSync(cur); } catch { return; } // does not exist yet: we create the rest ourselves
    if (st.isSymbolicLink()) throw new Error(`init: refusing to write through a symbolic link or junction: ${cur}`);
  }
}

function writeOwned(root, path, text, { force, log, dry }) {
  assertNoLinks(root, path);
  if (existsSync(path)) {
    const current = readFileSync(path, "utf8");
    if (current === text) { log(`  unchanged  ${path}`); return "unchanged"; }
    if (!current.includes(GENERATED) && !force) {
      log(`  SKIPPED    ${path} exists and was not generated by this kit; pass --force to replace it`);
      return "skipped";
    }
  }
  if (!dry) { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, text); }
  log(`  ${dry ? "would write" : "wrote"}     ${path}`);
  return "wrote";
}

function upsertBlock(root, path, block, { log, dry }) {
  assertNoLinks(root, path);
  const had = existsSync(path);
  const raw = had ? readFileSync(path, "utf8") : "";
  const eol = raw.includes("\r\n") ? "\r\n" : "\n"; // keep the user's line endings; only the marked block changes
  const current = raw.replace(/\r\n/g, "\n");
  const a = current.indexOf(BEGIN);
  const b = current.indexOf(END);
  let next;
  if (a !== -1 && b > a) next = current.slice(0, a) + block.trimEnd() + current.slice(b + END.length);
  else next = current + (current && !current.endsWith("\n\n") ? (current.endsWith("\n") ? "\n" : "\n\n") : "") + block;
  if (next === current) { log(`  unchanged  ${path}`); return "unchanged"; }
  if (!dry) { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, eol === "\n" ? next : next.replace(/\n/g, "\r\n")); }
  log(`  ${dry ? "would update" : had ? "updated" : "created"}   ${path} (block between markers)`);
  return "wrote";
}

/** Copy the kit's references folder file by file, checking every destination for links (cpSync would write through one). */
function copyReferences(root, dest, label, { dry, log }) {
  const src = join(PKG_ROOT, "references");
  const files = readdirSync(src, { withFileTypes: true }).filter((e) => e.isFile());
  for (const e of files) assertNoLinks(root, join(dest, e.name));
  assertNoLinks(root, dest);
  if (!dry) {
    mkdirSync(dest, { recursive: true });
    for (const e of files) writeFileSync(join(dest, e.name), readFileSync(join(src, e.name)));
  }
  log(`  ${dry ? "would copy" : "copied"}     references/ -> ${label}/`);
}

function ensureGitignore(root, { log, dry }) {
  const path = join(root, ".gitignore");
  assertNoLinks(root, path);
  const line = `${CACHE_DIR}/`;
  const current = existsSync(path) ? readFileSync(path, "utf8") : "";
  if (current.split(/\r?\n/).includes(line)) return;
  if (!dry) appendFileSync(path, `${current && !current.endsWith("\n") ? "\n" : ""}# Shopify docs cached by \`refresh\` (not ours to redistribute)\n${line}\n`);
  log(`  ${dry ? "would add" : "added"}      ${line} to .gitignore`);
}

export function init({ dir, agents, force = false, dry = false, log = console.log }) {
  const opts = { force, dry, log };
  const list = agents.includes("all") ? AGENTS : agents;
  const results = [];
  const needsRefs = list.some((a) => a !== "claude");
  for (const agent of list) {
    log(`${agent}:`);
    if (agent === "claude") {
      const base = join(dir, ".claude", "skills", skillName());
      // Pinned to this release: an installed rule must not start running a different (or hijacked) later version.
      const skill = read("SKILL.md").replaceAll(PLUGIN_CLI, `npx -y ${pkgName()}@${pkgVersion()}`);
      results.push(writeOwned(dir, join(base, "SKILL.md"), skill, opts));
      copyReferences(dir, join(base, "references"), `${join(".claude", "skills", skillName(), "references")}`, opts);
    } else if (agent === "codex") {
      results.push(upsertBlock(dir, join(dir, "AGENTS.md"), read("adapters/AGENTS.block.md"), opts));
    } else if (agent === "cursor") {
      results.push(writeOwned(dir, join(dir, ".cursor", "rules", "polaris-agent-kit.mdc"), read("adapters/cursor/polaris-agent-kit.mdc"), opts));
    } else if (agent === "copilot") {
      results.push(writeOwned(dir, join(dir, ".github", "instructions", "polaris-agent-kit.instructions.md"), read("adapters/copilot/polaris-agent-kit.instructions.md"), opts));
    } else if (agent === "windsurf") {
      results.push(writeOwned(dir, join(dir, ".windsurf", "rules", "polaris-agent-kit.md"), read("adapters/windsurf/polaris-agent-kit.md"), opts));
    }
  }
  if (needsRefs) copyReferences(dir, join(dir, KIT_DIR, "references"), `${KIT_DIR}/references`, opts);
  ensureGitignore(dir, opts);
  return { agents: list, results };
}

export async function runInit(argv) {
  const args = { dir: process.cwd(), agents: [], force: false, dry: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--agent") args.agents = String(argv[++i] ?? "").split(",").filter(Boolean);
    else if (a === "--dir") args.dir = argv[++i];
    else if (a === "--force") args.force = true;
    else if (a === "--dry-run") args.dry = true;
    else { console.error(`init: unknown option ${a}`); return 2; }
  }
  if (!args.agents.length) {
    if (!process.stdin.isTTY) {
      console.error(`init: pass --agent ${[...AGENTS, "all"].join("|")} (comma list allowed). No terminal to ask on.`);
      return 2;
    }
    const rl = createInterface({ input: process.stdin, output: process.stdout });
    const answer = await rl.question(`Which agent(s)? ${[...AGENTS, "all"].join(" | ")} (comma list): `);
    rl.close();
    args.agents = answer.split(",").map((s) => s.trim()).filter(Boolean);
  }
  const bad = args.agents.filter((a) => a !== "all" && !AGENTS.includes(a));
  if (bad.length || !args.agents.length) { console.error(`init: unknown agent ${bad.join(", ") || "(none)"}; choose from ${[...AGENTS, "all"].join(", ")}`); return 2; }
  if (!existsSync(args.dir)) { console.error(`init: ${args.dir} does not exist`); return 2; }
  init(args);
  console.log(`\nNext: ${args.agents.includes("claude") || args.agents.includes("all") ? "restart your agent so it sees the skill, " : ""}run \`npx -y ${pkgName()} refresh\` once for Shopify's current pages, then \`npx -y ${pkgName()} check\`.`);
  return 0;
}
